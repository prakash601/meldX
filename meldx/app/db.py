"""Async engine + session factory.

URL comes from DATABASE_URL env: Neon Postgres in prod, local Postgres or a
local SQLite file for development. Tests monkeypatch the URL (see tests/).
"""
import os
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncEngine, async_sessionmaker, create_async_engine
from sqlmodel import SQLModel
from sqlmodel.ext.asyncio.session import AsyncSession

DEFAULT_URL = "postgresql+asyncpg://meldx:meldx@localhost:5432/meldx"


def database_url() -> str:
    return os.environ.get("DATABASE_URL", DEFAULT_URL)


def is_sqlite(url: str | None = None) -> bool:
    return (url or database_url()).startswith("sqlite")


_engine: AsyncEngine | None = None


def get_engine() -> AsyncEngine:
    global _engine
    if _engine is None:
        _engine = create_async_engine(database_url(), pool_pre_ping=True)
    return _engine


def reset_engine() -> None:
    """Drop the cached engine. Test-only hook for URL monkeypatching."""
    global _engine
    if _engine is not None:
        _engine.sync_engine.dispose()
    _engine = None


async def get_session() -> AsyncIterator[AsyncSession]:
    async with session_scope() as session:
        yield session


@asynccontextmanager
async def session_scope() -> AsyncIterator[AsyncSession]:
    maker = async_sessionmaker(get_engine(), class_=AsyncSession, expire_on_commit=False)
    async with maker() as session:
        yield session


async def check_db() -> None:
    async with get_engine().connect() as conn:
        await conn.execute(text("SELECT 1"))


async def ensure_schema() -> None:
    """Create missing tables for local SQLite dev.

    The Alembic revision uses Postgres-native enum types, so `alembic upgrade
    head` cannot run against SQLite. For a local throwaway database the model
    metadata is the same source Alembic autogenerated from, so creating it
    directly is safe here. Postgres remains the schema authority in every other
    environment; the lifespan only calls this for a sqlite URL.
    """
    from meldx.app import models  # noqa: F401  -- register tables before create_all

    async with get_engine().begin() as conn:
        await conn.run_sync(SQLModel.metadata.create_all)
